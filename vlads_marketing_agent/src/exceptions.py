"""Власні винятки агента.

Окремі класи винятків дозволяють `main.py` та модулям відрізняти
"очікувані" помилки конфігурації/даних (які треба показати користувачу
зрозумілим повідомленням) від непередбачених багів (які варто підняти
далі зі стектрейсом).
"""

from __future__ import annotations


class AgentConfigError(Exception):
    """Помилка конфігурації: відсутня змінна середовища, битий YAML тощо.

    Виникає ще до звернення до будь-якого зовнішнього API, тому її
    завжди можна безпечно показати користувачу з порадою, що виправити.
    """


class AgentAuthError(Exception):
    """Помилка автентифікації (протермінований/відкликаний OAuth-токен тощо).

    На відміну від `AgentConfigError`, ця помилка виникає під час спроби
    звернутися до API, коли облікові дані виявились недійсними.
    """


class ExternalAPIError(Exception):
    """Помилка стороннього API після вичерпання всіх спроб повтору."""
